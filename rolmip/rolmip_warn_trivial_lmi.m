function rolmip_warn_trivial_lmi(expression,monomial)
% Warn before a constant coefficient or logical comparison is discarded.
if isnumeric(expression) || islogical(expression)
    warning('ROLMIP:TrivialLMI', ...
        ['Monomial %d produces a constant inequality with no decision variables. ' ...
         'It adds no decision-variable constraint. Check coefficient extraction ' ...
         'and use coeffs(P,''cell'') when indexing coefficients with braces.'], ...
        monomial);
end
end
